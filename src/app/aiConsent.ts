// ── AI-analysis consent ───────────────────────────────────────────────────────
// What people write here is sensitive information (PIPA Art. 23 민감정보,
// GDPR Art. 9 special-category data), and analyzing it means sending it to
// Anthropic in the US (PIPA Art. 28-8 overseas transfer). Korean law requires
// each of those to be consented to *separately* from everything else, with
// the purpose / items / retention / right-to-refuse spelled out at the moment
// of asking — so this is two independent checkboxes, not one "I agree".
//
// Declining is a real choice, not a dead end: entries are still recorded on
// the device (appendUnanalyzedEntry), they just never leave it. Every code
// path that calls /api/* checks hasAiConsent first — see the "think" case,
// requestReinterpretation, and GoalDirectionsPanel in App.tsx.
import * as React from "react";
import type { Store } from "./types";

// Bump when the consent wording or the list of recipients materially
// changes — a stored consent for an older version is treated as undecided,
// so people are asked again instead of being bound to text they never saw.
export const AI_CONSENT_VERSION = "2026-11-06";

export type AiConsent = {
  sensitive: boolean;
  overseas: boolean;
  decidedAt: string; // ISO timestamp — kept as the consent record
  version: string;
};

export function hasAiConsent(store: Pick<Store, "aiConsent">): boolean {
  const c = store.aiConsent;
  return !!c && c.version === AI_CONSENT_VERSION && c.sensitive && c.overseas;
}

// Never asked, or asked under an older version of the wording.
export function needsAiConsentDecision(store: Pick<Store, "aiConsent">): boolean {
  const c = store.aiConsent;
  return !c || c.version !== AI_CONSENT_VERSION;
}

export function sanitizeAiConsent(raw: any): AiConsent | null {
  if (!raw || typeof raw !== "object") return null;
  if (typeof raw.decidedAt !== "string" || typeof raw.version !== "string") return null;
  return { sensitive: raw.sensitive === true, overseas: raw.overseas === true, decidedAt: raw.decidedAt, version: raw.version };
}

// Lets deeply nested screens (GoalDirectionsPanel) read the decision without
// threading a prop through every screen in between. Defaults to false so a
// component rendered outside the provider fails closed, never open.
export const AiConsentContext = React.createContext<boolean>(false);

export function isKoreanLocale(): boolean {
  return typeof navigator !== "undefined" && (navigator.language || "").toLowerCase().startsWith("ko");
}

